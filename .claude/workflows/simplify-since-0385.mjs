const SCHEMA = {
  type: 'object',
  additionalProperties: false,
  properties: {
    batch: { type: 'string' },
    edited: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        properties: {
          file: { type: 'string' },
          summary: { type: 'string', description: 'what was simplified and why it is behavior-preserving' },
        },
        required: ['file', 'summary'],
      },
    },
    skipped: {
      type: 'array',
      description: 'notable cleanup opportunities deliberately NOT taken (too risky / out of scope), with reason',
      items: { type: 'string' },
    },
    risk: { type: 'string', enum: ['none', 'low', 'medium', 'high'] },
    notes: { type: 'string' },
  },
  required: ['batch', 'edited', 'risk', 'notes'],
}

function buildPrompt(batch, files) {
  return [
    `You are a code-simplifier working on the TeXRA repo. Simplify the source code that was ADDED or CHANGED since the v0.38.5 release tag, in EXACTLY these ${files.length} files (batch "${batch}"):`,
    files.map((f) => `  - ${f}`).join('\n'),
    ``,
    `## See what changed`,
    `For each file, inspect the committed diff since the release with:`,
    `  git diff v0.38.5..HEAD -- <file>`,
    `Read the full current file too (the diff shows only context). You may READ any other file in the repo for context, but you MUST NOT edit any file outside your list above.`,
    ``,
    `## Goal`,
    `Improve clarity, consistency, and maintainability of the NEW/CHANGED code while preserving behavior EXACTLY. Concretely, look for: duplicated logic that can be shared; unnecessary wrapper/indirection layers and trivial one-call factories (inline them); dead code, unused vars/params/imports left behind by the change; deeply nested conditionals that flatten cleanly; redundant type assertions or hand-rolled types where a derived/native type fits; verbose constructs with an idiomatic shorter form; comments that merely restate the code. Keep changes tightly scoped to the code the diff touched and its immediate surroundings. Do NOT refactor untouched pre-existing code far from the change.`,
    ``,
    `## Repo conventions (from CLAUDE.md / AGENTS.md), follow these`,
    `- Prose/comments: NO em dashes, no AI-slop, no narrating capabilities. Match the surrounding comment density and idiom. Prefer deleting a redundant comment over rewording it.`,
    `- Zod v4 is the single source of truth for data shapes: derive types via z.infer, compose with .extend()/.pick(), avoid z.custom<T>() when a real schema exists, prefer discriminatedUnion. Use .prefault()/.catch()/.nullish() idioms.`,
    `- Platform coupling: VS Code-free zones (src/agent, src/model, src/latex, src/tools, src/controllers, src/shared, src/transcript, webview frontends, etc.) must NOT import 'vscode'. Reach host services via platform() from '@platform'. Use isFile()/isDirectory() from '@utils/files/fsEntryType', isFileNotFoundError() from '@common/errors'.`,
    `- Avoid the discouraged factory/wrapper anti-patterns and flatten unnecessary abstraction layers (nodes create+run flows directly; delete unused wrappers rather than leaving re-exports).`,
    `- No render-time workarounds: renderers transform and display only, with no wall-clock reads, synthetic ids, DOM existence checks, or dedup at render time. If a renderer needs that, the upstream data model is missing it (flag it under "skipped", do not hack the renderer).`,
    `- TUI files (packages/cli/src/chat/tui/**): respect the Ink discipline. Root scrollback owns finalized root history via <Static> (dedupe by stable id), the live region stays minimal, renderers are stateless (view toggles live in shared signal state, not local component state), no line-count erase "fixes" for resize. Do not reinvent terminal scrolling/search. Headless/--print parity is sacred: never let Ink chrome leak into the non-TTY path.`,
    `- Prefer importing existing shared helpers over re-implementing; match existing naming and file idioms.`,
    ``,
    `## Hard constraints`,
    `- Edit ONLY the files in your list. Never touch files with unrelated uncommitted working-tree changes.`,
    `- Behavior-preserving ONLY. If a simplification is speculative, changes timing/ordering, or you are not confident it is equivalent, DO NOT make it. Record it under "skipped" instead. Zero edits is a perfectly valid outcome if the code is already clean.`,
    `- Do NOT run builds, typecheck, lint, tests, or any git state-changing command (no add/commit/stash/checkout). A central typecheck pass runs after you. Read-only git (diff/show/log) and read-only file tools are fine.`,
    `- Do NOT edit package.json, tsconfig, lockfiles, configs, or generated files.`,
    `- Leave your edits uncommitted in the working tree.`,
    ``,
    `## Quality bar`,
    `Apply your edits with the Edit/Write tools directly. After editing, re-read each file you changed to confirm it is coherent and imports are still correct. Then return the structured summary: every file you edited with a one-line behavior-preserving rationale, anything notable you skipped and why, an overall risk rating, and notes.`,
  ].join('\n')
}

phase('Simplify')
log(
  `Simplifying ${Object.values(BATCHES).reduce((n, f) => n + f.length, 0)} source files changed since v0.38.5 across ${Object.keys(BATCHES).length} disjoint batches`,
)

const entries = Object.entries(BATCHES)
const results = await parallel(
  entries.map(([batch, files]) => () =>
    agent(buildPrompt(batch, files), {
      label: `simplify:${batch}`,
      phase: 'Simplify',
      agentType: 'code-simplifier:code-simplifier',
      schema: SCHEMA,
    }).then((r) => r || { batch, edited: [], skipped: [], risk: 'none', notes: 'agent returned null (skipped or failed)' }),
  ),
)

const totalEdited = results.reduce((n, r) => n + (r.edited ? r.edited.length : 0), 0)
log(`Done: ${totalEdited} files edited across ${results.length} batches`)
return { results }
