log(`Pass 3: type-tightening ${BATCHES.reduce((n, b) => n + b.files.length, 0)} files across ${BATCHES.length} disjoint batches, 5-wide pool`)

const results = await runPool(BATCHES, 5, (batch) =>
  agent(buildPrompt(batch), {
    label: `types:${batch.name}`,
    phase: 'Tighten-types',
    agentType: 'code-simplifier:code-simplifier',
    schema: SCHEMA,
  }).then((r) => r || { batch: batch.name, edited: [], crossFile: [], skipped: [], risk: 'none', notes: 'agent returned null (skipped or failed)' }),
)

const totalEdited = results.reduce((n, r) => n + (r.edited ? r.edited.length : 0), 0)
const crossFile = results.flatMap((r) => r.crossFile || [])
log(`Pass 3 done: ${totalEdited} files edited; ${crossFile.length} cross-file follow-ups flagged`)
return { results }
