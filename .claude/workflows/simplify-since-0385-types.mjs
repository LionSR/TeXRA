function buildPrompt(batch) {
  const { name, files } = batch
  return [
    `You are a code-simplifier on the TeXRA repo, doing a focused TYPE-TIGHTENING pass on the source changed since the v0.38.5 release tag, in EXACTLY these ${files.length} files (batch "${name}"):`,
    files.map((f) => `  - ${f}`).join('\n'),
    ``,
    `These files were already cleaned for simplification and made more declarative in earlier passes; work from the current file state. This pass is ONLY about type ergonomics.`,
    ``,
    `## What changed`,
    `Inspect each file's committed diff since the release: \`git diff v0.38.5..HEAD -- <file>\`, and read the current file. You may READ any other file for context (especially to find the canonical type or Zod schema to reuse), but MUST NOT edit any file outside your list.`,
    ``,
    `## Goal: tighten types so nobody has to resolve them layer by layer`,
    `Find and fix places where a type is reconstructed or unwrapped indirectly instead of being stated once and reused:`,
    `- Derivation chains at the use site: \`Awaited<ReturnType<typeof fn>>\`, \`ReturnType<typeof fn>\`, \`Parameters<typeof fn>\`, deep indexed access (\`Foo['a']['b']['c']\`), \`typeof X[number]\` ladders. Replace with a single NAMED type. Annotate the function's return type (or export a named type from its source) so callers import that name instead of unwrapping. The repo already did this for CliToolUseResumeData and FollowUpQueue['drainItems']; apply the same idea.`,
    `- Inline anonymous object types restated at more than one site (params, returns, local annotations): hoist to one named \`type\`/\`interface\` and reference it everywhere within your files.`,
    `- Zod is the single source of truth: when a schema exists for a shape, use \`z.infer<typeof Schema>\` (exported once) as the type rather than a hand-written duplicate or a structural cast. Prefer \`.extend()\`/\`.pick()\` over restating fields; prefer \`z.discriminatedUnion\` over a union plus \`as\` casts.`,
    `- Casts that paper over missing types: remove \`as X\` / \`as unknown as X\` / \`as any\` that exist only because a type was not exported or a union was not discriminated. Replace with the real named type, a discriminated union, or a type guard. NEVER loosen a type (no new \`any\`, no widening) to make an error disappear; tighten only.`,
    `- Implicit \`any\` or overly-wide params/returns introduced by the diff: give them the precise type.`,
    ``,
    `## Repo conventions`,
    `- Zod v4 idioms (z.infer, .extend()/.pick(), discriminatedUnion, .prefault()/.catch()/.nullish()); co-locate types with schemas; add \`satisfies\` assertions when a type must stay in sync with an external shape. In model handlers, cast to the provider SDK's own types rather than hand-rolled structural shapes.`,
    `- Platform coupling: VS Code-free zones (src/agent, src/model, src/latex, src/tools, src/controllers, src/shared, src/transcript, webview frontends, packages/cli/**) must NOT import 'vscode'. Type-only imports from 'vscode' are still imports; do not add them in those zones.`,
    `- Prose/comments: no em dashes, no AI-slop. Match existing idioms.`,
    ``,
    `## Hard constraints`,
    `- Edit ONLY the files in your list. Never touch files with unrelated uncommitted working-tree changes (the user is concurrently editing some UI/style files; stay clear).`,
    `- RUNTIME-behavior-preserving ONLY. These are type-level edits: do not change runtime values, control flow, effects, or ordering. Renaming/exporting a type and replacing a derivation with its name is fine; changing what a function actually returns at runtime is NOT.`,
    `- Keep the WHOLE repo typecheck-clean. You may EXPORT a type from one of your files and rewrite derivations WITHIN your files. If a real win requires editing a consumer in a file OUTSIDE your batch (e.g. to import the newly-exported name, or because changing a return type would ripple), DO NOT do it blindly. Make only the in-batch part that stays type-clean, and record the cross-file follow-up under "crossFile" with the exact type name and the consumer files/sites. A central typecheck runs after you and the orchestrator will reconcile cross-file items.`,
    `- Do NOT run builds, typecheck, lint, tests, or any git state-changing command. Read-only git (diff/show/log) and read-only file tools are fine.`,
    `- Do NOT edit package.json, tsconfig, lockfiles, configs, or generated files. Leave edits uncommitted.`,
    ``,
    `## Quality bar`,
    `Apply edits with Edit/Write. After editing, re-read each changed file and mentally re-check that every type still resolves and you introduced no \`any\`/cast. Be conservative: if you are unsure a type change keeps the whole repo compiling, put it under "crossFile" or "skipped" instead of applying it. Zero edits is a valid outcome. Return the structured summary: each edited file with a one-line rationale, cross-file follow-ups, anything skipped, an overall risk rating, and notes.`,
  ].join('\n')
}

async function runPool(items, concurrency, worker) {
  const results = new Array(items.length)
  let nextIndex = 0
  async function runner() {
    while (true) {
      const i = nextIndex++
      if (i >= items.length) return
      results[i] = await worker(items[i], i)
    }
  }
  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, runner))
  return results
}

