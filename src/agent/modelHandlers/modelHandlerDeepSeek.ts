// Third-party imports
import OpenAI from 'openai';

// Local file imports
import { ModelHandlerOpenAI } from './modelHandlerOpenAI';
import { BaseReasoningStreamAggregator } from './BaseReasoningStreamAggregator';
import type { NormalizedUsage } from '@agent/types/NormalizedUsage';

// Type imports
import type {
  CreateResponseOptions,
  DeepSeekToolCall,
} from './types/IModelHandler';
import type {
  ChatCompletion,
  ChatCompletionMessageParam,
} from 'openai/resources/chat/completions';

// TODO: prompt_cache_hit_tokens can also be used here to correct the price and response usage computation in the base class (just overwrite the computePrice and computeResponseUsage methods with a revalues responseUsage.prompt_tokens_details?.cached_tokens and then call the super methods)
// DEEPSEEK RESPONSE USAGE FORMAT:
// usage
// object
// Usage statistics for the completion request.
// completion_tokens
// integer
// REQUIRED
// Number of tokens in the generated completion.
// prompt_tokens
// integer
// REQUIRED
// Number of tokens in the prompt. It equals prompt_cache_hit_tokens + prompt_cache_miss_tokens.
// prompt_cache_hit_tokens
// integer
// REQUIRED
// Number of tokens in the prompt that hits the context cache.
// prompt_cache_miss_tokens
// integer
// REQUIRED
// Number of tokens in the prompt that misses the context cache.
// total_tokens
// integer
// REQUIRED
// Total number of tokens used in the request (prompt + completion).
// completion_tokens_details
// object
// Breakdown of tokens used in a completion.
// reasoning_tokens
// integer
// Tokens generated by the model for reasoning.

/**
 * Handler for DeepSeek models using OpenAI-compatible API.
 */
export class ModelHandlerDeepSeek extends ModelHandlerOpenAI<DeepSeekToolCall> {
  protected override get toolCallProvider(): string {
    return 'deepseek';
  }

  protected override get usageProvider(): NormalizedUsage['provider'] {
    return 'deepseek';
  }

  /**
   * DeepSeek expects string content format instead of array format.
   */
  protected override formatAssistantContent(text: string): string {
    return text;
  }

  protected createStreamingAggregator(): BaseReasoningStreamAggregator | null {
    return new BaseReasoningStreamAggregator();
  }

  /**
   * Override createResponse to preprocess messages for Deepseek models
   */
  async createResponse(
    options: CreateResponseOptions<ChatCompletionMessageParam, OpenAI>,
  ): Promise<ChatCompletion> {
    const { messages } = options;
    // Preprocess messages to merge consecutive messages and convert content to strings
    const processedMessages = this.prepareNormalizedMessages(
      messages,
      {
        mergeConsecutiveRoles: true,
        convertContentToString: true,
      },
      'Deepseek',
    );

    // Call the parent implementation with the processed messages
    return super.createResponse({
      ...options,
      messages: processedMessages,
    });
  }
}
