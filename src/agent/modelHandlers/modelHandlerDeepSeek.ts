// DEEPSEEK RESPONSE USAGE FORMAT:
// usage
// object
// Usage statistics for the completion request.
// completion_tokens
// integer
// REQUIRED
// Number of tokens in the generated completion.
// prompt_tokens
// integer
// REQUIRED
// Number of tokens in the prompt. It equals prompt_cache_hit_tokens + prompt_cache_miss_tokens.
// prompt_cache_hit_tokens
// integer
// REQUIRED
// Number of tokens in the prompt that hits the context cache.
// prompt_cache_miss_tokens
// integer
// REQUIRED
// Number of tokens in the prompt that misses the context cache.
// total_tokens
// integer
// REQUIRED
// Total number of tokens used in the request (prompt + completion).
// completion_tokens_details
// object
// Breakdown of tokens used in a completion.
// reasoning_tokens
// integer
// Tokens generated by the model for reasoning.

/**
 * Extended assistant message type with DeepSeek's reasoning_content field.
 * This is required for thinking mode with tool calls.
 */
type DeepSeekAssistantMessage = ChatCompletionAssistantMessageParam & {
  reasoning_content?: string;
};

/**
 * Handler for DeepSeek models using OpenAI-compatible API.
 *
 * Supports DeepSeek's thinking mode with tool calls. When thinking mode is enabled:
 * - The model outputs reasoning_content along with tool_calls
 * - The reasoning_content must be included in assistant messages during tool-use cycles
 * - The reasoning_content should be cleared when a new user turn begins
 *
 * @see https://api-docs.deepseek.com/guides/thinking_with_tools
 */
export class ModelHandlerDeepSeek extends ModelHandlerOpenAI<DeepSeekToolCall> {
  /**
   * Stores the last reasoning_content from a model response.
   * This is used to include reasoning_content in follow-up tool-use messages
   * as required by DeepSeek's thinking mode API.
   */
  private lastReasoningContent: string | null = null;

  protected override get toolCallProvider(): string {
    return 'deepseek';
  }

  protected override get usageProvider(): NormalizedUsage['provider'] {
    return 'deepseek';
  }

  /**
   * DeepSeek expects string content format instead of array format.
   */
  protected override formatAssistantContent(text: string): string {
    return text;
  }

  protected createStreamingAggregator(): BaseReasoningStreamAggregator | null {
    return new BaseReasoningStreamAggregator();
  }

  /**
   * Process thinking block and capture reasoning_content for tool-use cycles.
   *
   * DeepSeek's thinking mode requires reasoning_content to be included in
   * assistant messages during tool-use cycles. This method captures it
   * for use in createToolUseFollowUpMessages.
   */
  override processThinkingBlock(
    responseObject: any,
    workspaceState?: AgentWorkspaceState,
  ): string | null {
    const reasoning = super.processThinkingBlock(responseObject, workspaceState);
    // Store reasoning for tool-use follow-up messages
    this.lastReasoningContent = reasoning;
    return reasoning;
  }

  /**
   * Clears the stored reasoning content.
   * Should be called when a new user turn begins to avoid including
   * stale reasoning from previous turns.
   */
  clearReasoningContent(): void {
    this.lastReasoningContent = null;
  }

  /**
   * Creates tool-use follow-up messages with reasoning_content support.
   *
   * For DeepSeek thinking mode, the assistant message must include
   * reasoning_content when tool calls are made. This allows the model
   * to continue its reasoning chain across tool-use cycles.
   *
   * Note: DeepSeek models don't support attachments in tool results,
   * so we pass the result directly without attachment extraction.
   */
  override async createToolUseFollowUpMessages(
    _client: OpenAI | undefined,
    call: DeepSeekToolCall,
    result: Record<string, unknown>,
    _workspaceState?: AgentWorkspaceState,
    text?: string,
  ): Promise<ChatCompletionMessageParam[]> {
    const toolCall = this.normalizeToolCall(call.raw);

    // Build assistant message with reasoning_content for thinking mode
    const callMsg: DeepSeekAssistantMessage = {
      role: 'assistant',
      tool_calls: [toolCall],
    };

    // Include reasoning_content if available (required for thinking mode)
    if (this.lastReasoningContent) {
      callMsg.reasoning_content = this.lastReasoningContent;
      // Clear after use since it should only be included once per response
      this.lastReasoningContent = null;
    }

    if (text) {
      callMsg.content = this.formatAssistantContent(text);
    }

    const resultMsg = {
      role: 'tool' as const,
      tool_call_id: toolCall.id,
      content: JSON.stringify(result),
    };

    return [callMsg as ChatCompletionMessageParam, resultMsg];
  }

  /**
   * Creates batched tool-use follow-up messages for multiple parallel tool calls.
   *
   * For DeepSeek thinking mode, all tool calls from a single model response
   * should be in ONE assistant message with reasoning_content, followed by
   * individual tool result messages.
   *
   * Note: DeepSeek models don't support attachments in tool results,
   * so we pass results directly without attachment extraction.
   *
   * @param calls - Array of tool calls from the model response
   * @param results - Array of results corresponding to each call
   * @param text - Optional text content to include in the assistant message
   */
  async createBatchedToolUseFollowUpMessages(
    calls: DeepSeekToolCall[],
    results: Record<string, unknown>[],
    text?: string,
  ): Promise<ChatCompletionMessageParam[]> {
    // Build assistant message with ALL tool calls and reasoning_content
    const toolCalls = calls.map((call) => this.normalizeToolCall(call.raw));

    const callMsg: DeepSeekAssistantMessage = {
      role: 'assistant',
      tool_calls: toolCalls,
    };

    // Include reasoning_content if available (required for thinking mode)
    if (this.lastReasoningContent) {
      callMsg.reasoning_content = this.lastReasoningContent;
      // Clear after use since it should only be included once per response
      this.lastReasoningContent = null;
    }

    if (text) {
      callMsg.content = this.formatAssistantContent(text);
    }

    const messages: ChatCompletionMessageParam[] = [
      callMsg as ChatCompletionMessageParam,
    ];

    // Add individual tool result messages
    for (let i = 0; i < calls.length; i++) {
      const call = calls[i];
      const result = results[i];

      messages.push({
        role: 'tool' as const,
        tool_call_id: call.callId,
        content: JSON.stringify(result),
      });
    }

    return messages;
  }

  /**
   * Override createResponse to preprocess messages for Deepseek models
   */
  async createResponse(
    options: CreateResponseOptions<ChatCompletionMessageParam, OpenAI>,
  ): Promise<ChatCompletion> {
    const { messages } = options;
    // Preprocess messages to merge consecutive messages and convert content to strings
    const processedMessages = this.prepareNormalizedMessages(
      messages,
      {
        mergeConsecutiveRoles: true,
        convertContentToString: true,
      },
      'Deepseek',
    );

    // Call the parent implementation with the processed messages
    return super.createResponse({
      ...options,
      messages: processedMessages,
    });
  }
}
