// DEEPSEEK RESPONSE USAGE FORMAT:
// usage
// object
// Usage statistics for the completion request.
// completion_tokens
// integer
// REQUIRED
// Number of tokens in the generated completion.
// prompt_tokens
// integer
// REQUIRED
// Number of tokens in the prompt. It equals prompt_cache_hit_tokens + prompt_cache_miss_tokens.
// prompt_cache_hit_tokens
// integer
// REQUIRED
// Number of tokens in the prompt that hits the context cache.
// prompt_cache_miss_tokens
// integer
// REQUIRED
// Number of tokens in the prompt that misses the context cache.
// total_tokens
// integer
// REQUIRED
// Total number of tokens used in the request (prompt + completion).
// completion_tokens_details
// object
// Breakdown of tokens used in a completion.
// reasoning_tokens
// integer
// Tokens generated by the model for reasoning.

/**
 * Handler for DeepSeek models using OpenAI-compatible API.
 */
export class ModelHandlerDeepSeek extends ModelHandlerOpenAI {
  protected createStreamingAggregator(): StreamingAggregator | null {
    return new DeepSeekStreamAggregator();
  }

  /**
   * Process thinking blocks for DeepSeek models
   * @param responseObject The raw response object from the model
   * @param workspaceState Optional workspaceState to update with the thinking block
   * @returns The extracted reasoning_content or null if none
   */
  processThinkingBlock(
    responseObject: any,
    workspaceState?: AgentWorkspaceState,
  ): string | null {
    if (!responseObject) {
      return null;
    }

    // Extract reasoning content from DeepSeek response
    let reasoningContent = null;

    // Check for reasoning_content based on DeepSeek API structure
    // Example from their site: response.choices[0].message.reasoning_content
    if (
      responseObject.choices &&
      responseObject.choices.length > 0 &&
      responseObject.choices[0].message
    ) {
      const message = responseObject.choices[0].message;

      // Primary location according to DeepSeek docs
      if (message.reasoning_content) {
        reasoningContent = message.reasoning_content;
        this.logger.debug(
          'Found reasoning_content in choices[0].message.reasoning_content',
        );

        // If workspaceState is provided and we have reasoning content,
        // store it in the workspaceState for future use (similar to Anthropic thinking blocks)
        if (workspaceState && !workspaceState.reasoning.thinkingAdded) {
          // Create a thinking block in the same format as Anthropic for consistency
          const thinkingBlock = {
            type: 'thinking',
            thinking: reasoningContent,
          };

          workspaceState.reasoning.thinkingBlocks = [thinkingBlock];
          workspaceState.reasoning.thinkingAdded = true;
          // this.logger.debug('Added reasoning content to workspaceState');
        }
        // For deepseek mode thinking content should not be attached back to the message as a content item.
        // Nevertheless one can include one in a bare way...
      }
    }
    if (!reasoningContent) {
      return null;
    }

    // Log preview of thinking content (assuming it's a string)
    this.logger.debug(
      `DeepSeek reasoning content preview: ${reasoningContent.substring(0, K_SLICE)}...`,
    );

    // Return the reasoning content (already a string for DeepSeek)
    return reasoningContent;
  }

  extractToolUse(responseObject: any): string | null {
    const toolCalls = responseObject?.choices?.[0]?.message?.tool_calls;
    if (Array.isArray(toolCalls) && toolCalls.length > 0) {
      return JSON.stringify(toolCalls[0], null, 2);
    }
    const func = responseObject?.choices?.[0]?.message?.function_call;
    if (func) {
      return JSON.stringify(func, null, 2);
    }
    return null;
  }

  async createToolUseFollowUpMessages(
    _client: OpenAI | undefined,
    callArg: ChatCompletionMessageToolCall | ChatCompletionMessage.FunctionCall | any,
    result: Record<string, unknown>,
    _workspaceState?: AgentWorkspaceState,
    text?: string,
  ): Promise<ChatCompletionMessageParam[]> {
    // Handle both native tool call and legacy parsed payload
    const call = callArg as ChatCompletionMessageToolCall | ChatCompletionMessage.FunctionCall;
    const id = (call as any)?.id ?? (call as any)?.tool_call_id ?? 'unknown-id';
    const name = (call as any)?.name ?? (call as any)?.function?.name ?? 'unknown';
    
    // Use original if it's a complete ChatCompletionMessageToolCall, otherwise normalize
    let toolCall: ChatCompletionMessageToolCall;
    const isCompleteToolCall = (call as ChatCompletionMessageToolCall)?.type === 'function' && 
                                (call as ChatCompletionMessageToolCall)?.id &&
                                (call as any)?.function;
    if (isCompleteToolCall) {
      toolCall = call as ChatCompletionMessageToolCall;  // ✅ Use ORIGINAL
    } else {
      toolCall = this.normalizeToolCall(id, name, call);  // Fallback
    }
    const callMsg: ChatCompletionAssistantMessageParam = {
      role: 'assistant',
      tool_calls: [toolCall],
    };
    if (text) {
      callMsg.content = text;
    }
    const { attachments, sanitizedResult } = extractToolAttachments(result);
    if (attachments.length > 0) {
      (sanitizedResult as Record<string, unknown>).attachmentSummary =
        `Attachments available:\n${describeAttachments(attachments).join(
          '\n',
        )}\nUse the read_file tool to download them.`;
    }
    const resultMsg: ChatCompletionToolMessageParam = {
      role: 'tool',
      tool_call_id: toolCall.id ?? id,
      content: JSON.stringify(sanitizedResult),
    };
    return [callMsg, resultMsg];
  }

  /**
   * Override createResponse to preprocess messages for Deepseek models
   */
  async createResponse(
    options: CreateResponseOptions<ChatCompletionMessageParam>,
  ): Promise<any> {
    const { messages } = options;
    // Preprocess messages to merge consecutive messages and convert content to strings
    const processedMessages = this.prepareNormalizedMessages(
      messages,
      {
        mergeConsecutiveRoles: true,
        convertContentToString: true,
      },
      'Deepseek',
    );

    // Call the parent implementation with the processed messages
    return super.createResponse({
      ...options,
      messages: processedMessages,
    });
  }
}

type ChatCompletionMessageWithReasoning = ChatCompletionMessage & {
  reasoning_content?: string;
};

interface AggregatedToolCall {
  id: string;
  function: ChatCompletionMessageFunctionToolCall['function'];
}

class DeepSeekStreamAggregator implements StreamingAggregator {
  private readonly contentParts: string[] = [];
  private readonly reasoningParts: string[] = [];
  private readonly toolCalls = new Map<number, AggregatedToolCall>();
  private functionCall: ChatCompletionMessage['function_call'] = null;
  private lastChunkWithChoices: ChatCompletionChunk | undefined;
  private usageChunk: ChatCompletionChunk | undefined;

  appendContent(delta: string): void {
    if (delta) {
      this.contentParts.push(delta);
    }
  }

  appendReasoning(delta: string): void {
    if (delta) {
      this.reasoningParts.push(delta);
    }
  }

  consumeChunk(chunk: ChatCompletionChunk): void {
    if (chunk.choices.length > 0) {
      this.lastChunkWithChoices = chunk;
    }
    if (chunk.usage) {
      this.usageChunk = chunk;
    }

    const choice = chunk.choices[0];
    if (!choice) {
      return;
    }

    const { delta } = choice;

    if (Array.isArray(delta.tool_calls)) {
      for (const call of delta.tool_calls) {
        const existing = this.toolCalls.get(call.index) ?? {
          id: '',
          function: { name: '', arguments: '' },
        };
        if (call.id) {
          existing.id += call.id;
        }
        if (call.function?.name) {
          existing.function.name += call.function.name;
        }
        if (call.function?.arguments) {
          existing.function.arguments += call.function.arguments;
        }
        this.toolCalls.set(call.index, existing);
      }
    }

    if (delta.function_call) {
      const { name = '', arguments: args = '' } = delta.function_call;
      const current = this.functionCall ?? { name: '', arguments: '' };
      this.functionCall = {
        name: `${current.name}${name}`,
        arguments: `${current.arguments}${args}`,
      };
    }
  }

  finalize(fallback?: ChatCompletion): ChatCompletion {
    const base = fallback ?? this.buildFallbackResponse();
    const primaryChoice = base.choices[0] ?? {
      index: 0,
      message: { role: 'assistant', content: '', refusal: null },
      finish_reason: 'stop',
      logprobs: null,
    };
    const fallbackMessage = primaryChoice.message;

    const mergedMessage: ChatCompletionMessageWithReasoning = {
      ...fallbackMessage,
      role: 'assistant',
      content: this.getFullContent(),
      refusal: fallbackMessage.refusal ?? null,
    };

    const reasoning = this.getFullReasoning();
    if (reasoning) {
      mergedMessage.reasoning_content = reasoning;
    }

    const toolCalls = this.buildToolCalls();
    if (toolCalls.length > 0) {
      mergedMessage.tool_calls = toolCalls;
    }

    if (
      this.functionCall &&
      (this.functionCall.name.length > 0 ||
        this.functionCall.arguments.length > 0)
    ) {
      mergedMessage.function_call = this.functionCall;
    }

    const mergedChoice = {
      ...primaryChoice,
      index: primaryChoice.index ?? 0,
      message: mergedMessage,
      finish_reason: primaryChoice.finish_reason ?? 'stop',
      logprobs: primaryChoice.logprobs ?? null,
    };

    const usageCandidate =
      base.usage ?? this.usageChunk?.usage ?? this.lastChunkWithChoices?.usage;
    const usage = usageCandidate === null ? undefined : usageCandidate;

    return {
      ...base,
      choices: [mergedChoice],
      usage,
    };
  }

  getFullContent(): string {
    return this.contentParts.join('');
  }

  getFullReasoning(): string {
    return this.reasoningParts.join('');
  }

  private buildToolCalls(): ChatCompletionMessageFunctionToolCall[] {
    const toolCalls: ChatCompletionMessageFunctionToolCall[] = [];
    for (const [index, call] of this.toolCalls.entries()) {
      if (!call.id && !call.function.name && !call.function.arguments) {
        continue;
      }
      toolCalls.push({
        id: call.id || `tool_call_${index}`,
        type: 'function',
        function: {
          name: call.function.name,
          arguments: call.function.arguments,
        },
      });
    }
    return toolCalls;
  }

  private buildFallbackResponse(): ChatCompletion {
    const chunk = this.lastChunkWithChoices ?? this.usageChunk;
    if (!chunk) {
      return {
        id: '',
        object: 'chat.completion',
        created: Math.floor(Date.now() / 1000),
        model: '',
        choices: [
          {
            index: 0,
            message: {
              role: 'assistant',
              content: this.getFullContent(),
              refusal: null,
            },
            finish_reason: 'stop',
            logprobs: null,
          },
        ],
      };
    }

    const choice = chunk.choices[0];
    const usage = chunk.usage === null ? undefined : chunk.usage;

    return {
      id: chunk.id,
      object: 'chat.completion',
      created: chunk.created,
      model: chunk.model,
      system_fingerprint: chunk.system_fingerprint,
      usage,
      choices: [
        {
          index: choice?.index ?? 0,
          message: {
            role: 'assistant',
            content: this.getFullContent(),
            refusal: null,
          },
          finish_reason: choice?.finish_reason ?? 'stop',
          logprobs: choice?.logprobs ?? null,
        },
      ],
    };
  }
}
