let isRegistered = false;

/**
 * Legacy codicon-to-canonical aliases for backward compatibility with persisted
 * icon names (e.g. in localStorage, settings files, or telemetry events that
 * may still reference the old names). The static migration handled the source
 * code; this map handles data that lives outside the repo.
 *
 * Canonical names first shipped in extension v0.39.10 on 2026-07-29. Retain
 * these aliases through 2026-10-29; remove them only after supported persisted
 * and external extension icon names can no longer contain the legacy spellings
 * tracked in #6981.
 */
const LEGACY_ICON_ALIASES: Readonly<Record<string, keyof typeof icons>> =
  Object.freeze({
    close: 'xmark',
    diff: 'code-compare',
    edit: 'pencil',
    error: 'circle-exclamation',
    refresh: 'rotate-right',
    save: 'floppy-disk',
    search: 'magnifying-glass',
    'settings-gear': 'gear',
    tools: 'screwdriver-wrench',
    warning: 'triangle-exclamation',
  });

function texraIconResolver(name: string): string {
  const canonical = LEGACY_ICON_ALIASES[name] ?? name;
  const icon = icons[canonical as keyof typeof icons];
  return icon ? `data:image/svg+xml,${encodeURIComponent(iconSvg(icon))}` : '';
}

export function registerTeXRAWebAwesomeIcons(): void {
  if (isRegistered) return;

  registerIconLibrary(TEXRA_ICON_LIBRARY, { resolver: texraIconResolver });
  // WA's own internal components resolve icons through the 'default' library,
  // which WA hardcodes to a live CDN (ka-f.fontawesome.com) — confirmed via
  // DevTools network capture. Reusing the same offline resolver here means no
  // host (extension, desktop, webview, trace-viewer) depends on that CDN for
  // any icon, anywhere.
  registerIconLibrary('default', { resolver: texraIconResolver });
  isRegistered = true;
}

interface WaIconOptions {
  readonly id?: string;
  readonly canvas?: 'auto' | 'fixed' | 'roomy' | 'square';
  // 'start' / 'end' for wa-button; 'icon' for wa-callout / wa-card.
  readonly slot?: 'start' | 'end' | 'icon';
  readonly className?: string;
  readonly variant?: 'solid' | 'regular';
  readonly label?: string;
  // Native `title` tooltip. Purely visual — a decorative icon with a hover
  // tooltip stays `aria-hidden` (only `label` exposes it to assistive tech).
  readonly title?: string;
}

// Lit template for <wa-icon>. Decorative icons stay hidden from assistive
// technology; icon-only controls pass a label as required by Web Awesome.
export function waIcon(
  name: TeXRAIconName,
  options: WaIconOptions = {},
): TemplateResult {
  return html`<wa-icon
    id=${ifDefined(options.id)}
    library=${TEXRA_ICON_LIBRARY}
    name=${name}
    variant=${options.variant ?? 'solid'}
    canvas=${options.canvas ?? 'auto'}
    slot=${ifDefined(options.slot)}
    class=${ifDefined(options.className)}
    label=${ifDefined(options.label)}
    title=${ifDefined(options.title)}
    aria-hidden=${ifDefined(options.label == null ? 'true' : undefined)}
  ></wa-icon>`;
}
