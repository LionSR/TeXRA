#!/usr/bin/env node
// Install the local git hooks: the format-staged hook chained ahead of
// pre-commit's shim.
//
// `pre-commit install` writes .git/hooks/pre-commit. Auto-staging Prettier
// output must happen BEFORE pre-commit's shim runs — once it does, unstaged
// changes are already stashed and index rewrites become dangerous (see
// scripts/format-staged.mjs). So .git/hooks/pre-commit is a small shim that
// formats and stages first, then execs pre-commit's shim, relocated to
// .git/hooks/pre-commit.chain.
//
// Idempotent and safe to re-run. `pre-commit install` refuses to overwrite
// our shim, so after re-running it by hand, re-run this installer
// (`npm run hooks:install`).

import { spawnSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';

const MARKER = 'texra-format-staged';
const PRE_COMMIT_MARKER = 'File generated by pre-commit';

const SHIM = `#!/bin/sh
# ${MARKER}: stage Prettier output, then chain to pre-commit (issue #9955).
# Installed by scripts/install-local-hooks.mjs; re-run \`npm run hooks:install\`
# after any manual \`pre-commit install\` (which does not know about this hook).
node scripts/format-staged.mjs
# A manual \`pre-commit install\` moves this shim to pre-commit.legacy
# (migration mode). In that case pre-commit's hook-impl is already running
# and executes its hooks after the legacy hook returns — chaining again
# would recurse, so just stop here.
if [ -n "$PRE_COMMIT_RUNNING_LEGACY" ]; then
  exit 0
fi
chain="$(git rev-parse --git-path hooks)/pre-commit.chain"
if [ -x "$chain" ]; then
  exec "$chain" "$@"
fi
exit 0
`;

const read = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : null);

function main() {
  const gitPathResult = spawnSync('git', ['rev-parse', '--git-path', 'hooks'], {
    encoding: 'utf8',
  });
  if (gitPathResult.status !== 0) {
    throw new Error(
      `git rev-parse --git-path hooks failed: ${gitPathResult.stderr}`,
    );
  }
  const hooksDir = resolve(gitPathResult.stdout.trim());
  const hookPath = join(hooksDir, 'pre-commit');
  const chainPath = join(hooksDir, 'pre-commit.chain');
  mkdirSync(hooksDir, { recursive: true });

  const hasPreCommit = spawnSync('pre-commit', ['--version']).status === 0;

  let hook = read(hookPath);
  if (hook && !hook.includes(MARKER) && !hook.includes(PRE_COMMIT_MARKER)) {
    console.error(`Refusing to overwrite an unrecognized hook at ${hookPath}.`);
    process.exit(1);
  }

  if (hasPreCommit) {
    // Always regenerate pre-commit's shim. The generated shim embeds the
    // Python interpreter it was installed from, so a fresh install also
    // refreshes a stale chain left behind by an earlier environment.
    // pre-commit refuses to overwrite our shim, hence --overwrite in that
    // case; the fresh shim is re-chained below.
    const hookIsOurs = hook?.includes(MARKER);
    const args = ['install', ...(hookIsOurs ? ['--overwrite'] : [])];
    const install = spawnSync('pre-commit', args, { stdio: 'inherit' });
    if (install.status !== 0) {
      console.error('`pre-commit install` failed.');
      process.exit(1);
    }
    hook = read(hookPath);
  }

  if (hook?.includes(PRE_COMMIT_MARKER)) {
    renameSync(hookPath, chainPath);
  }

  // A manual `pre-commit install` relocates this shim to pre-commit.legacy.
  // Once we are installed as the primary hook again, that stale copy would
  // be invoked by hook-impl before every commit — drop it. A legacy hook we
  // did not write stays untouched.
  const legacyPath = `${hookPath}.legacy`;
  if (read(legacyPath)?.includes(MARKER)) {
    rmSync(legacyPath);
  }

  writeFileSync(hookPath, SHIM);
  chmodSync(hookPath, 0o755);

  console.log(`Installed ${hookPath} (format-staged).`);
  if (existsSync(chainPath)) {
    console.log(`Chained pre-commit's shim as ${chainPath}.`);
  } else {
    console.log(
      'pre-commit not found; only the format hook was installed. Install ' +
        'pre-commit (`python -m pip install pre-commit`) and re-run ' +
        '`npm run hooks:install` for the remaining hooks.',
    );
  }
}

main();
