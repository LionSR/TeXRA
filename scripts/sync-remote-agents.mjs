#!/usr/bin/env node
/**
 * Sync reference-agents/ YAMLs → remote_agents table.
 *
 * Reads every YAML in reference-agents/ (and Lean4/), extracts name,
 * description, tools, and agentCategory, then either:
 *   1. Generates SQL to paste into the Supabase SQL Editor  (default)
 *   2. Executes directly via `supabase db execute`            (--exec)
 *
 * Usage:
 *   node scripts/sync-remote-agents.mjs              # print SQL to stdout
 *   node scripts/sync-remote-agents.mjs --exec       # run via supabase CLI
 *   node scripts/sync-remote-agents.mjs -o out.sql   # write SQL to file
 *
 * Storage path conventions:
 *   - Workflow agents       → workflow/{name}.yaml
 *   - Tool-use agents       → tool_use/{name}.yaml
 *   - Lean tool-use agents  → tool-use-lean/{name}.yaml
 */

import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { resolve, basename, dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { parseArgs } from 'util';
import { execSync } from 'child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');
const refDir = resolve(rootDir, 'reference-agents');

// ---------------------------------------------------------------------------
// Minimal YAML parser (enough for top-level name/description/settings.tools)
// Avoids adding a dependency just for this script.
// ---------------------------------------------------------------------------

function parseYamlShallow(text) {
  const result = {};

  // name
  const nameMatch = text.match(/^name:\s*(.+)$/m);
  if (nameMatch) result.name = nameMatch[1].trim();

  // description (may be multi-line with >- or | but usually single-line)
  const descMatch = text.match(/^description:\s*(.+)$/m);
  if (descMatch) result.description = descMatch[1].trim();

  // agentCategory
  const catMatch = text.match(/^\s*agentCategory:\s*(.+)$/m);
  if (catMatch) result.agentCategory = catMatch[1].trim();

  // inherits
  const inheritsMatch = text.match(/^inherits:\s*(.+)$/m);
  if (inheritsMatch) result.inherits = inheritsMatch[1].trim();

  // tools (array of strings or objects with name)
  const toolsIdx = text.indexOf('  tools:');
  if (toolsIdx !== -1) {
    const toolSection = text.slice(toolsIdx);
    const toolLines = toolSection.split('\n').slice(1); // skip "  tools:" line
    const tools = [];
    for (const line of toolLines) {
      // Stop at next non-tool line (not indented enough or new section)
      if (/^\S/.test(line) || /^\s{0,3}\S/.test(line)) break;
      const itemMatch = line.match(/^\s+-\s+(\S+)/);
      if (itemMatch) {
        const val = itemMatch[1];
        // Skip YAML comments
        if (!val.startsWith('#')) tools.push(val);
      }
    }
    if (tools.length) result.tools = tools;
  }

  return result;
}

// ---------------------------------------------------------------------------
// Discover all agent YAMLs
// ---------------------------------------------------------------------------

/** @returns {{ file: string, subdir: string }[]} */
function discoverYamls() {
  const yamls = [];

  // Top-level reference-agents/
  for (const f of readdirSync(refDir)) {
    if (f.endsWith('.yaml')) {
      yamls.push({ file: join(refDir, f), subdir: '' });
    }
  }

  // Subdirectories (Lean4/, etc.)
  for (const d of readdirSync(refDir, { withFileTypes: true })) {
    if (!d.isDirectory()) continue;
    const subPath = join(refDir, d.name);
    for (const f of readdirSync(subPath)) {
      if (f.endsWith('.yaml')) {
        yamls.push({ file: join(subPath, f), subdir: d.name });
      }
    }
  }

  return yamls;
}

// ---------------------------------------------------------------------------
// Determine storage path from agent metadata
// ---------------------------------------------------------------------------

function storagePath(name, agentCategory, subdir) {
  if (subdir === 'Lean4') return `tool-use-lean/${name}.yaml`;
  if (agentCategory === 'toolUse') return `tool_use/${name}.yaml`;
  return `workflow/${name}.yaml`;
}

function visibility(subdir) {
  if (subdir === 'Lean4') return `ARRAY['researcher', 'lean']`;
  return `ARRAY['researcher']`;
}

function sqlEscape(s) {
  return s.replace(/'/g, "''");
}

// ---------------------------------------------------------------------------
// Build SQL
// ---------------------------------------------------------------------------

function buildSql(agents) {
  const lines = [];

  lines.push('-- Auto-generated by scripts/sync-remote-agents.mjs');
  lines.push(`-- Generated: ${new Date().toISOString().slice(0, 10)}`);
  lines.push('-- Run this in the Supabase SQL Editor or via: supabase db execute');
  lines.push('');
  lines.push('ALTER TABLE remote_agents ADD COLUMN IF NOT EXISTS tools TEXT[] DEFAULT NULL;');
  lines.push('');

  // Group by category for readability
  const workflow = agents.filter((a) => a.agentCategory !== 'toolUse');
  const toolUse = agents.filter(
    (a) => a.agentCategory === 'toolUse' && a.subdir !== 'Lean4',
  );
  const lean = agents.filter(
    (a) => a.agentCategory === 'toolUse' && a.subdir === 'Lean4',
  );

  const sections = [
    { label: 'Workflow agents', items: workflow },
    { label: 'Tool-use agents', items: toolUse },
    { label: 'Tool-use agents (Lean)', items: lean },
  ];

  for (const { label, items } of sections) {
    if (!items.length) continue;
    lines.push(`-- ${'-'.repeat(75)}`);
    lines.push(`-- ${label}`);
    lines.push(`-- ${'-'.repeat(75)}`);
    lines.push('');

    for (const a of items) {
      const toolsVal = a.tools
        ? `ARRAY[${a.tools.map((t) => `'${t}'`).join(', ')}]`
        : 'NULL';

      const isToolUse = a.agentCategory === 'toolUse';
      const updateTools = isToolUse ? ',\n  tools          = EXCLUDED.tools' : '';

      lines.push(`INSERT INTO remote_agents (name, description, storage_path, visibility, agent_category, tools)`);
      lines.push(`VALUES (`);
      lines.push(`  '${sqlEscape(a.name)}',`);
      lines.push(`  '${sqlEscape(a.description || '')}',`);
      lines.push(`  '${a.storagePath}',`);
      lines.push(`  ${a.vis},`);
      lines.push(`  '${a.agentCategory || 'workflow'}',`);
      lines.push(`  ${toolsVal}`);
      lines.push(`)`);
      lines.push(`ON CONFLICT (name) DO UPDATE SET`);
      lines.push(`  description    = EXCLUDED.description,`);
      lines.push(`  storage_path   = EXCLUDED.storage_path,`);
      lines.push(`  visibility     = EXCLUDED.visibility,`);
      lines.push(`  agent_category = EXCLUDED.agent_category${updateTools};`);
      lines.push('');
    }
  }

  // Cleanup stale entries that were renamed
  lines.push('-- ---------------------------------------------------------------------------');
  lines.push('-- Cleanup stale entries (renamed/removed agents)');
  lines.push('-- ---------------------------------------------------------------------------');
  lines.push('');
  lines.push("DELETE FROM remote_agents WHERE name = 'lean'; -- renamed to leanOrchestrator");
  lines.push('');

  lines.push('-- Verify');
  lines.push(`SELECT name, description, agent_category, tools, visibility`);
  lines.push(`FROM remote_agents ORDER BY agent_category, name;`);

  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

const { values: flags } = parseArgs({
  options: {
    exec: { type: 'boolean', default: false },
    output: { type: 'string', short: 'o' },
  },
  strict: false,
});

const yamls = discoverYamls();

// First pass: parse all YAMLs
const parsedMap = new Map();
for (const { file, subdir } of yamls) {
  const text = readFileSync(file, 'utf8');
  const parsed = parseYamlShallow(text);
  if (!parsed.name) parsed.name = basename(file, '.yaml');
  if (!parsed.agentCategory) parsed.agentCategory = 'workflow';
  parsed._subdir = subdir;
  parsedMap.set(parsed.name, parsed);
}

// Second pass: resolve inheritance for missing descriptions/tools
const agents = [];
for (const parsed of parsedMap.values()) {
  if (!parsed.description && parsed.inherits) {
    const parent = parsedMap.get(parsed.inherits);
    if (parent?.description) {
      parsed.description = parent.description;
    }
  }

  agents.push({
    ...parsed,
    subdir: parsed._subdir,
    storagePath: storagePath(parsed.name, parsed.agentCategory, parsed._subdir),
    vis: visibility(parsed._subdir),
  });
}

// Sort: workflow first, then tool-use, then lean; alphabetical within groups
agents.sort((a, b) => {
  const catOrder = (x) =>
    x.agentCategory === 'toolUse' ? (x.subdir === 'Lean4' ? 2 : 1) : 0;
  const ca = catOrder(a),
    cb = catOrder(b);
  if (ca !== cb) return ca - cb;
  return a.name.localeCompare(b.name);
});

const sql = buildSql(agents);

if (flags.output) {
  writeFileSync(flags.output, sql + '\n');
  console.log(`Wrote ${agents.length} agents to ${flags.output}`);
} else if (flags.exec) {
  console.log(`Syncing ${agents.length} agents via supabase CLI...`);
  try {
    execSync(`supabase db execute --stdin`, {
      input: sql,
      stdio: ['pipe', 'inherit', 'inherit'],
    });
    console.log('Done.');
  } catch {
    console.error(
      'Failed. Install Supabase CLI: npm i -g supabase\n' +
        'Then link: supabase link --project-ref <ref>',
    );
    process.exit(1);
  }
} else {
  console.log(sql);
}
